"""v6: smaller copies of every image the floor draws, so the first screen (the whole exhibition at a glance) loads light
and a close view does not decode 2560-px files. Run from archive/:  python3 tools/lod_images.py
Reads assets/ and media/ (never writes there) and writes lod/<same path> at most 480 px wide (JPEG q72) and, for files
wider than about 1500 px, lod/m/<same path> at 1280 px (q80), plus js/lod.js, the list of paths that have copies.
The floor shows the small copy and steps up (small, middle, full) only when an image is drawn larger than the copy it
shows (js/app.js upgradeImages). Rooms and the gallery always use the full files. Re-run after new images."""
import json, pathlib, re, subprocess
from PIL import Image

ARC = pathlib.Path(__file__).resolve().parent.parent
MAXW, Q = 480, 72
MIDW, MQ = 1280, 80
data = json.loads(subprocess.run(["node", "-e", "global.window={};global.document={baseURI:'file:///'};for(const f of process.argv.slice(1))require(f);console.log(JSON.stringify(window.AR))",
                                  str(ARC / "js/data.js"), str(ARC / "js/assets.js")], capture_output=True, text=True, check=True).stdout)
paths = set()
for p in data["pieces"]:
    for m in p.get("media", []):
        if m.get("type") == "video": paths.add(m["poster"])
        elif m.get("src"): paths.add(m["src"])
for k, s in data["assetSlots"].items():
    for f in (s.get("file"), s.get("fallback")):
        if f: paths.add(f)
done = {}
for rel in sorted(paths):
    src = ARC / rel
    if not src.exists() or src.suffix.lower() not in (".jpg", ".jpeg", ".png"): continue
    im = Image.open(src); w, h = im.size
    if w <= MAXW * 1.2: continue  # already small
    dst = ARC / "lod" / rel
    dst = dst.with_suffix(".jpg")
    dst.parent.mkdir(parents=True, exist_ok=True)
    im.convert("RGB").resize((MAXW, round(h * MAXW / w)), Image.LANCZOS).save(dst, quality=Q, optimize=True, progressive=True)
    done[rel] = {"lod": str(dst.relative_to(ARC)), "w": MAXW}
    if w > MIDW * 1.2:
        mid = (ARC / "lod/m" / rel).with_suffix(".jpg"); mid.parent.mkdir(parents=True, exist_ok=True)
        im.convert("RGB").resize((MIDW, round(h * MIDW / w)), Image.LANCZOS).save(mid, quality=MQ, optimize=True, progressive=True)
        done[rel].update(mid=str(mid.relative_to(ARC)), mw=MIDW)
(ARC / "js/lod.js").write_text("/* Generated by tools/lod_images.py: floor images that have a small copy in lod/ (path → copy). Do not edit. */\n"
                               "(function () { const AR = (window.AR = window.AR || {}); AR.lod = " + json.dumps(done, ensure_ascii=False, indent=0) + "; })();\n", encoding="utf-8")
mids = [v["mid"] for v in done.values() if "mid" in v]
print(f"{len(done)} copies in lod/, {sum((ARC / v['lod']).stat().st_size for v in done.values()) / 1e3:.0f} KB; {len(mids)} middle copies in lod/m/, "
      f"{sum((ARC / m).stat().st_size for m in mids) / 1e3:.0f} KB (full files: {sum((ARC / k).stat().st_size for k in done) / 1e3:.0f} KB)")
